"""Bundle Pokedex, Abilities and Items JSONs into <script src> JS files.

Like moves-db.js, the data ships as plain JS files because the cards are
standalone HTML usually opened via file://, where fetch() of local JSON is
blocked by CORS. Re-run whenever the source JSONs change:

    python3 scripts/build_pokedex_db.py
"""
import json
import os

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUNDLES = [
    ([os.path.join(REPO_ROOT, 'v3.0', 'Pokedex')], 'window.ALL_POKEMON',
     os.path.join(REPO_ROOT, 'pokedex-db.js'),
     lambda e: (e.get('Number', 0), e.get('Name', ''))),
    ([os.path.join(REPO_ROOT, 'v3.0', 'Abilities')], 'window.ALL_ABILITIES',
     os.path.join(REPO_ROOT, 'abilities-db.js'),
     lambda e: e.get('Name', '')),
    # Items merge core and homebrew; on duplicate names the first dir wins
    ([os.path.join(REPO_ROOT, 'v3.0', 'Items'),
      os.path.join(REPO_ROOT, 'Homebrew', 'Items')], 'window.ALL_ITEMS',
     os.path.join(REPO_ROOT, 'items-db.js'),
     lambda e: e.get('Name', '')),
]


def resolve_item_sprites(entries):
    """Fill every item's Image with an existing ItemSprites file.

    Tried in order: the declared Image, <_id>.png, the canonical berry name
    for homebrew "Cherry" renames, and finally the pokeball placeholder.
    """
    sprites = set(os.listdir(os.path.join(REPO_ROOT, 'images', 'ItemSprites')))
    for entry in entries:
        candidates = [
            entry.get('Image'),
            entry.get('_id', '') + '.png',
            entry.get('_id', '').replace('-cherry', '-berry') + '.png',
        ]
        entry['Image'] = next(
            (c for c in candidates if c and c in sprites), 'pokeball.png')


def main():
    for src_dirs, global_name, out_file, sort_key in BUNDLES:
        entries = []
        seen_names = set()
        for src_dir in src_dirs:
            for filename in sorted(os.listdir(src_dir)):
                if not filename.endswith('.json'):
                    continue
                with open(os.path.join(src_dir, filename), encoding='utf-8') as f:
                    entry = json.load(f)
                if entry.get('Name') in seen_names:
                    continue
                seen_names.add(entry.get('Name'))
                entries.append(entry)

        if global_name == 'window.ALL_ITEMS':
            resolve_item_sprites(entries)

        entries.sort(key=sort_key)

        with open(out_file, 'w', encoding='utf-8') as f:
            f.write('// Generated by scripts/build_pokedex_db.py - do not edit by hand\n')
            f.write(global_name + ' = ')
            json.dump(entries, f, ensure_ascii=False, separators=(',', ':'))
            f.write(';\n')

        size_kb = os.path.getsize(out_file) / 1024
        print(f'Wrote {len(entries)} entries to {out_file} ({size_kb:.0f} KB)')


if __name__ == '__main__':
    main()
