"""Bundle every move in v3.0/Moves into moves-db.js.

The Pokerole cards are standalone HTML files usually opened via file://,
where fetch() of local JSON is blocked by CORS. A plain <script src>
tag is not, so the full move list ships as a JS file assigning
window.ALL_MOVES. Re-run this script whenever the move JSONs change:

    python3 scripts/build_moves_db.py
"""
import json
import os

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOVES_DIR = os.path.join(REPO_ROOT, 'v3.0', 'Moves')
OUT_FILE = os.path.join(REPO_ROOT, 'moves-db.js')


def main():
    moves = []
    for filename in sorted(os.listdir(MOVES_DIR)):
        if not filename.endswith('.json'):
            continue
        with open(os.path.join(MOVES_DIR, filename), encoding='utf-8') as f:
            moves.append(json.load(f))

    moves.sort(key=lambda m: m.get('Name', ''))

    with open(OUT_FILE, 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/build_moves_db.py - do not edit by hand\n')
        f.write('window.ALL_MOVES = ')
        json.dump(moves, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n')

    size_kb = os.path.getsize(OUT_FILE) / 1024
    print(f'Wrote {len(moves)} moves to {OUT_FILE} ({size_kb:.0f} KB)')


if __name__ == '__main__':
    main()
